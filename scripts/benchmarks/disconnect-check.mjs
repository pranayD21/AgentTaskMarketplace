#!/usr/bin/env node
// Real HTTP disconnect after the isolated MCP server accepts a task. No paid services.
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { randomBytes, generateKeyPairSync } from 'node:crypto';
import fs from 'node:fs/promises';
import http from 'node:http';
import os from 'node:os';
import path from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { createClient, parseRpcResponse } from '../buyer.mjs';

const root = path.resolve(import.meta.dirname, '../..');
const output = path.resolve(process.argv[2] ?? 'docs/buyer/runs/disconnect-v1.json');
const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'atm-disconnect-'));
let server;
let proxy;
let disconnected = false;
let postCalls = 0;
let acceptedTask;
let phase = 'startup';

async function listen(listener) {
  await new Promise((resolve, reject) => {
    listener.once('error', reject);
    listener.listen(0, '127.0.0.1', resolve);
  });
  return listener.address().port;
}
async function reservePort() {
  const listener = http.createServer();
  const port = await listen(listener);
  await new Promise(resolve => listener.close(resolve));
  return port;
}
async function invoke(args, endpoint, key) {
  return new Promise((resolve, reject) => {
    // This credential is generated by the isolated server and never printed or persisted.
    const child = spawn(process.execPath, [path.join(root, 'scripts/buyer.mjs'), ...args], {
      cwd: root,
      env: { ...process.env, MARKETPLACE_URL: endpoint, ATM_API_KEY: key },
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    let out = ''; let err = '';
    child.stdout.on('data', chunk => { out += chunk; });
    child.stderr.on('data', chunk => { err += chunk; });
    const timer = setTimeout(() => { child.kill('SIGTERM'); reject(new Error('Isolated buyer command timed out')); }, 40000);
    child.once('error', error => { clearTimeout(timer); reject(error); });
    child.once('exit', code => {
      clearTimeout(timer);
      try { resolve({ code, data: JSON.parse(code === 0 ? out : err) }); }
      catch { reject(new Error('Isolated buyer returned an unexpected response')); }
    });
  });
}
try {
  const port = await reservePort();
  const origin = `http://127.0.0.1:${port}`;
  const judgePublic = generateKeyPairSync('x25519').publicKey.export({ type: 'spki', format: 'der' }).subarray(-32).toString('base64');
  server = spawn(process.execPath, ['node_modules/mcp-use/dist/bin.js', 'dev', '--port', String(port), '--no-open', '--no-inspector'], {
    cwd: path.join(root, 'apps/marketplace-mcp'), detached: true, stdio: 'ignore',
    env: {
      ...process.env, DB_MODE: 'memory', PAYMENT_MODE: 'mock', INKBOX_API_KEY: '',
      STRIPE_SECRET_KEY: '', STRIPE_PROFILE_ID: '',
      INSFORGE_API_KEY: 'isolated-unused-key', INSFORGE_BASE_URL: 'http://127.0.0.1:1',
      ANTHROPIC_API_KEY: '', SERVER_KEK_B64: randomBytes(32).toString('base64'),
      JUDGE_PUBLIC_KEY_B64: judgePublic, JUDGE_KEY_ID: 'judge-disconnect-fixture',
      JUDGE_REGISTRATION_SECRET: randomBytes(24).toString('hex'),
      BASE_URL: origin, PORT: String(port),
    },
  });
  let healthy = false;
  for (let attempt = 0; attempt < 80; attempt++) {
    if (server.exitCode !== null) throw new Error('Isolated marketplace exited during startup');
    try {
      const health = await fetch(`${origin}/api/health`, { signal: AbortSignal.timeout(500) }).then(r => r.json());
      if (health.payments === 'mock' && health.db?.startsWith('MEMORY')) { healthy = true; break; }
    } catch { /* wait for this test's child only */ }
    await delay(250);
  }
  assert.ok(healthy, 'isolated MEMORY/MOCK marketplace did not become ready');
  proxy = http.createServer(async (request, response) => {
    try {
      const chunks = [];
      for await (const chunk of request) chunks.push(chunk);
      const body = Buffer.concat(chunks).toString();
      const rpc = JSON.parse(body);
      const isPost = rpc.method === 'tools/call' && rpc.params?.name === 'post_task';
      if (isPost) postCalls++;
      const headers = { ...request.headers };
      delete headers.host; delete headers.connection; delete headers['content-length'];
      const upstream = await fetch(`${origin}/mcp`, { method: 'POST', headers, body, signal: AbortSignal.timeout(30000) });
      const text = await upstream.text();
      if (isPost && !disconnected) {
        assert.equal(upstream.status, 200);
        const envelope = parseRpcResponse(text, upstream.headers.get('content-type') ?? '', rpc.id);
        assert.ok(!envelope.isError);
        const result = envelope.structuredContent ?? JSON.parse(envelope.content.find(c => c.type === 'text').text);
        acceptedTask = result.task.task_id;
        assert.ok(acceptedTask);
        disconnected = true;
        // Acceptance has already committed upstream. Deliver headers and an incomplete body,
        // then destroy the real TCP response so the client cannot read the accepted task ID.
        response.writeHead(200, { 'content-type': 'application/json', 'content-length': String(Buffer.byteLength(text) + 100) });
        response.flushHeaders();
        response.write('{');
        setTimeout(() => response.destroy(), 30);
        return;
      }
      const forwarded = {};
      for (const name of ['content-type', 'mcp-session-id']) {
        const value = upstream.headers.get(name); if (value) forwarded[name] = value;
      }
      response.writeHead(upstream.status, forwarded);
      response.end(text);
    } catch {
      response.destroy();
    }
  });
  const proxyPort = await listen(proxy);
  const endpoint = `http://127.0.0.1:${proxyPort}/mcp`;
  const registration = createClient(endpoint);
  phase = 'registration';
  await registration.initialize();
  const identity = await registration.tool('register_agent', { kind: 'buyer', display_name: 'isolated-disconnect-fixture', spend_cap_cents: 100 });
  const promptFile = path.join(temporary, 'input.txt');
  await fs.writeFile(promptFile, 'Return the single word fixture.', { mode: 0o600 });
  const failed = await invoke(['post', '--prompt-file', promptFile, '--expect', 'fixture', '--max', '100'], endpoint, identity.api_key);
  phase = 'disconnect result';
  assert.equal(failed.code, 1);
  assert.equal(failed.data.error.code, 'CONNECTION_FAILED');
  assert.match(failed.data.error.next_action, /use tasks/);
  assert.ok(disconnected);
  // Every invoke is a new OS process: recover with the same identity after the failed one exits.
  const recovered = await invoke(['tasks'], endpoint, identity.api_key);
  phase = 'recovery inventory';
  assert.equal(recovered.code, 0);
  assert.equal(recovered.data.tasks.length, 1);
  assert.equal(recovered.data.tasks[0].task_id, acceptedTask);
  assert.equal(recovered.data.tasks[0].status, 'OPEN');
  const balance = await invoke(['whoami'], endpoint, identity.api_key);
  phase = 'reservation';
  assert.equal(balance.data.spend.reserved_cents, 100);
  assert.equal(balance.data.spend.spent_cents, 0);
  assert.equal(postCalls, 1);
  const cancelled = await invoke(['cancel', acceptedTask], endpoint, identity.api_key);
  phase = 'cancellation';
  assert.equal(cancelled.code, 0);
  const finalBalance = await invoke(['whoami'], endpoint, identity.api_key);
  const finalTask = await invoke(['task', acceptedTask], endpoint, identity.api_key);
  assert.equal(finalBalance.data.spend.reserved_cents, 0);
  assert.equal(finalBalance.data.spend.spent_cents, 0);
  assert.equal(finalTask.data.task.status, 'CANCELLED');
  assert.equal(finalTask.data.task.payment.state, 'MOCK');
  const report = {
    schema: 'atm-disconnect-check/v1', checked_at: new Date().toISOString(), result: 'PASS',
    transport: 'real loopback HTTP, truncated response after upstream post acceptance',
    server: 'real marketplace MCP server', storage: 'MEMORY', payments: 'MOCK',
    client: 'real buyer CLI in separate OS processes', post_calls: postCalls,
    task_id: acceptedTask, recovered_task_count: recovered.data.tasks.length,
    observed_error: failed.data.error.code, reserved_after_acceptance_cents: 100,
    reserved_after_cleanup_cents: 0, spent_cents: 0,
    final_task_status: 'CANCELLED', final_payment_state: 'MOCK',
    external_model_calls: 0, external_payment_calls: 0,
    limits: ['No real Stripe charge', 'No hosted service fault injected', 'No seller inference or judge evaluation'],
  };
  await fs.mkdir(path.dirname(output), { recursive: true });
  await fs.writeFile(output, `${JSON.stringify(report, null, 2)}\n`);
  console.log(JSON.stringify(report));
} catch (error) {
  // Keep child output and payloads private even on failure.
  console.error(`Disconnect check failed at ${phase}: ${error instanceof assert.AssertionError ? 'assertion failed' : error.message}`);
  process.exitCode = 1;
} finally {
  proxy?.closeAllConnections(); proxy?.close();
  if (server?.pid && server.exitCode === null) {
    try { process.kill(-server.pid, 'SIGTERM'); } catch { /* already stopped */ }
  }
  await fs.rm(temporary, { recursive: true, force: true });
}
