#!/usr/bin/env node
// Isolated real-MCP job recovery and aggregation; deterministic fake model, no paid services.
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import fs from 'node:fs/promises';
import http from 'node:http';
import os from 'node:os';
import path from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { generateKeypair, toB64 } from '../../packages/crypto/src/index.ts';
import { createRunner } from '../../packages/runner-core/src/index.ts';
import { createClient, parseRpcResponse } from '../buyer.mjs';

const root = path.resolve(import.meta.dirname, '../..');
const output = path.resolve(process.argv[2] ?? 'docs/buyer/runs/job-v03.json');
const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'atm-disconnect-'));
let server;
let proxy;
let disconnected = false;
let postCalls = 0;
let acceptedTask;
let phase = 'startup';

async function listen(listener) {
  await new Promise((resolve, reject) => {
    listener.once('error', reject);
    listener.listen(0, '127.0.0.1', resolve);
  });
  return listener.address().port;
}
async function reservePort() {
  const listener = http.createServer();
  const port = await listen(listener);
  await new Promise(resolve => listener.close(resolve));
  return port;
}
async function invoke(args, endpoint, key) {
  return new Promise((resolve, reject) => {
    // This credential is generated by the isolated server and never printed or persisted.
    const child = spawn(process.execPath, [path.join(root, 'scripts/buyer.mjs'), ...args], {
      cwd: root,
      env: { ...process.env, MARKETPLACE_URL: endpoint, ATM_API_KEY: key, ATM_JOB_DIR: temporary },
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    let out = ''; let err = '';
    child.stdout.on('data', chunk => { out += chunk; });
    child.stderr.on('data', chunk => { err += chunk; });
    const timer = setTimeout(() => { child.kill('SIGTERM'); reject(new Error('Isolated buyer command timed out')); }, 40000);
    child.once('error', error => { clearTimeout(timer); reject(error); });
    child.once('exit', code => {
      clearTimeout(timer);
      try { resolve({ code, data: JSON.parse(code === 0 ? out : err) }); }
      catch { reject(new Error('Isolated buyer returned an unexpected response')); }
    });
  });
}
try {
  const port = await reservePort();
  const origin = `http://127.0.0.1:${port}`;
  const judgeKey = generateKeypair();
  const judgePublic = toB64(judgeKey.publicKey);
  const judgeSecret = randomBytes(24).toString('hex');
  server = spawn(process.execPath, ['node_modules/mcp-use/dist/bin.js', 'dev', '--port', String(port), '--no-open', '--no-inspector'], {
    cwd: path.join(root, 'apps/marketplace-mcp'), detached: true, stdio: 'ignore',
    env: {
      ...process.env, DB_MODE: 'memory', PAYMENT_MODE: 'mock', INKBOX_API_KEY: '',
      STRIPE_SECRET_KEY: '', STRIPE_PROFILE_ID: '',
      INSFORGE_API_KEY: 'isolated-unused-key', INSFORGE_BASE_URL: 'http://127.0.0.1:1',
      ANTHROPIC_API_KEY: '', SERVER_KEK_B64: randomBytes(32).toString('base64'),
      JUDGE_PUBLIC_KEY_B64: judgePublic, JUDGE_KEY_ID: 'judge-disconnect-fixture',
      JUDGE_REGISTRATION_SECRET: judgeSecret,
      BASE_URL: origin, PORT: String(port),
    },
  });
  let healthy = false;
  for (let attempt = 0; attempt < 80; attempt++) {
    if (server.exitCode !== null) throw new Error('Isolated marketplace exited during startup');
    try {
      const health = await fetch(`${origin}/api/health`, { signal: AbortSignal.timeout(500) }).then(r => r.json());
      if (health.payments === 'mock' && health.db?.startsWith('MEMORY')) { healthy = true; break; }
    } catch { /* wait for this test's child only */ }
    await delay(250);
  }
  assert.ok(healthy, 'isolated MEMORY/MOCK marketplace did not become ready');
  proxy = http.createServer(async (request, response) => {
    try {
      const chunks = [];
      for await (const chunk of request) chunks.push(chunk);
      const body = Buffer.concat(chunks).toString();
      const rpc = JSON.parse(body);
      const isPost = rpc.method === 'tools/call' && rpc.params?.name === 'post_task';
      if (isPost) postCalls++;
      const headers = { ...request.headers };
      delete headers.host; delete headers.connection; delete headers['content-length'];
      const upstream = await fetch(`${origin}/mcp`, { method: 'POST', headers, body, signal: AbortSignal.timeout(30000) });
      const text = await upstream.text();
      if (isPost && !disconnected) {
        assert.equal(upstream.status, 200);
        const envelope = parseRpcResponse(text, upstream.headers.get('content-type') ?? '', rpc.id);
        assert.ok(!envelope.isError);
        const result = envelope.structuredContent ?? JSON.parse(envelope.content.find(c => c.type === 'text').text);
        acceptedTask = result.task.task_id;
        assert.ok(acceptedTask);
        disconnected = true;
        // Acceptance has already committed upstream. Deliver headers and an incomplete body,
        // then destroy the real TCP response so the client cannot read the accepted task ID.
        response.writeHead(200, { 'content-type': 'application/json', 'content-length': String(Buffer.byteLength(text) + 100) });
        response.flushHeaders();
        response.write('{');
        setTimeout(() => response.destroy(), 30);
        return;
      }
      const forwarded = {};
      for (const name of ['content-type', 'mcp-session-id']) {
        const value = upstream.headers.get(name); if (value) forwarded[name] = value;
      }
      response.writeHead(upstream.status, forwarded);
      response.end(text);
    } catch {
      response.destroy();
    }
  });
  const proxyPort = await listen(proxy);
  const endpoint = `http://127.0.0.1:${proxyPort}/mcp`;
  const registration = createClient(endpoint);
  phase = 'registration';
  await registration.initialize();
  const identity = await registration.tool('register_agent', { kind: 'buyer', display_name: 'isolated-job-fixture', spend_cap_cents: 200 });
  const inputFile = path.join(temporary, 'input.json');
  await fs.writeFile(inputFile, JSON.stringify({ instruction:'Double the numeric value in each record.',records:[{id:'a',value:3},{id:'b',value:4},{id:'c',value:5},{id:'d',value:6}],rubric:{kind:'contains_text',expected_text:'output'} }),{mode:0o600});
  const planned=await invoke(['job-plan',inputFile,'--name','fixture','--parts','2','--budget','200'],endpoint,identity.api_key);
  assert.equal(planned.code,0); assert.equal(postCalls,0);
  const failed=await invoke(['job-run','fixture','--timeout','1'],endpoint,identity.api_key);
  phase='job response loss'; assert.equal(failed.code,1); assert.equal(failed.data.error.code,'CONNECTION_FAILED'); assert.ok(disconnected);
  const recovered=await invoke(['job-run','fixture','--timeout','1'],endpoint,identity.api_key);
  phase='job restart'; assert.equal(recovered.code,0); assert.equal(recovered.data.parts.length,2); assert.equal(postCalls,2);
  assert.equal(recovered.data.server_budget.reserved_cents,200);
  assert.ok(recovered.data.parts.some(p=>p.task_id===acceptedTask));
  const journal=JSON.parse(await fs.readFile(path.join(temporary,'fixture.json'),'utf8'));
  const judgeIdentity=await registration.tool('register_agent',{kind:'judge',display_name:'isolated-job-judge',judge_secret:judgeSecret});
  const judgeClient=createClient(endpoint,judgeIdentity.api_key); await judgeClient.initialize();
  const privateMarker='PRIVATE_SYNTHETIC_REASON_MUST_NOT_PUBLISH';
  const sellerIds=[];
  for(const part of journal.plan.parts){
    const sellerIdentity=await registration.tool('register_agent',{kind:'seller',display_name:'isolated-job-seller'});
    sellerIds.push(sellerIdentity.agent_id);
    const seller=createClient(endpoint,sellerIdentity.api_key);await seller.initialize();
    await seller.tool('register_seller',{models:[{model_id:'qwen3:8b'}],runtime:'node-unsandboxed'});
    const answer=JSON.stringify(JSON.parse(part.context).map(record=>({id:record.id,output:record.value*2})));
    const host={getSecret:async()=>undefined,now:Date.now,fetch:async url=>new Response(JSON.stringify(String(url).endsWith('/api/tags')?{models:[{name:'qwen3:8b',digest:'synthetic'}]}:{message:{content:answer},eval_count:20}),{headers:{'content-type':'application/json'}})};
    const runner=createRunner(host); const key=runner.getPublicKey();
    const {claim}=await seller.tool('claim_task',{task_id:journal.tasks[part.part_key],model_id:'qwen3:8b',runner_pubkey_b64:key.public_key_b64,runner_key_id:key.key_id});
    const produced=await runner.runTask(claim.seller_envelope,{ollama_url:'http://fixture.invalid',model_id:claim.model_id,buyer_public_key:claim.buyer_public_key,judge_public_key:claim.judge_public_key});
    const {seller_usage,...result}=produced;
    await seller.tool('submit_result',{task_id:claim.task_id,claim_id:claim.claim_id,...result});
    const {package:review}=await judgeClient.tool('fetch_review_package');
    phase='deterministic judge';
    const judged=await runner.judgeTask(review.payload_enc_judge,review.result_enc_judge,{buyer_public_key:review.buyer_public_key,commitment_sha256:review.commitment_sha256},judgeKey);
    assert.equal(judged.verdict,'APPROVE');
    await judgeClient.tool('submit_verdict',{task_id:claim.task_id,result_id:review.result_id,...judged,reason_public:privateMarker});
  }
  const complete=await invoke(['job-run','fixture','--timeout','1'],endpoint,identity.api_key);
  phase='verified aggregate'; assert.equal(complete.code,0); assert.equal(complete.data.status,'COMPLETE'); assert.equal(postCalls,2);
  const aggregate=await invoke(['job-result','fixture'],endpoint,identity.api_key);
  assert.equal(aggregate.code,0);assert.deepEqual(aggregate.data.records,[{id:'a',output:6},{id:'b',output:8},{id:'c',output:10},{id:'d',output:12}]);
  assert.ok(aggregate.data.parts.every(p=>p.included&&p.commitment_verified));
  const balance=await invoke(['whoami'],endpoint,identity.api_key);
  assert.equal(balance.data.spend.reserved_cents,0);assert.equal(balance.data.spend.spent_cents,200);
  assert.equal(aggregate.data.server_budget.reserved_cents,0);assert.equal(aggregate.data.server_budget.spent_cents,200);
  const publicResponse=await fetch(`${origin}/api/dashboard`).then(r=>r.text());assert.ok(!publicResponse.includes(privateMarker));
  const report={schema:'atm-job-check/v1',checked_at:new Date().toISOString(),result:'PASS',storage:'MEMORY',payments:'MOCK',runtime:'node-unsandboxed',model:'deterministic test double',
    job_id:journal.job_id,task_ids:aggregate.data.parts.map(p=>p.task_id),seller_ids:sellerIds,parts:2,aggregated_records:aggregate.data.records.length,
    transport:'real HTTP response truncated after first part acceptance; fresh CLI processes resume the original journal',post_calls:postCalls,
    authorized_budget_cents:200,reserved_after_acceptance_cents:200,reserved_final_cents:0,spent_final_cents:200,
    commitments_verified:true,original_order_preserved:true,public_reason_marker_absent:true,external_model_calls:0,external_payment_calls:0,
    limits:['Synthetic local model; no inference quality claim','Two identities on one machine, not a physical multi-computer demo','No hosted faults or real Stripe calls']};
  await fs.mkdir(path.dirname(output), { recursive: true });
  await fs.writeFile(output, `${JSON.stringify(report, null, 2)}\n`);
  console.log(JSON.stringify(report));
} catch (error) {
  // Keep child output and payloads private even on failure.
  console.error(`Job check failed at ${phase}: ${error instanceof assert.AssertionError ? 'assertion failed' : error.message}`);
  process.exitCode = 1;
} finally {
  proxy?.closeAllConnections(); proxy?.close();
  if (server?.pid && server.exitCode === null) {
    try { process.kill(-server.pid, 'SIGTERM'); } catch { /* already stopped */ }
  }
  await fs.rm(temporary, { recursive: true, force: true });
}
